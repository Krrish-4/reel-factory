"""Derive shot-size bands from the corpus, instead of inventing them.

    python refs/shot-bands.py            # rewrite refs/shot-bands.json
    python refs/shot-bands.py --show

WHY THIS EXISTS
---------------
"Frame the face at 0.25" would be exactly the mistake rule V names: a single
remembered number quoted as a target when the references disagree. They do
disagree — per-reel medians run 0.121 to 0.412 — because they are not all
shooting the same shot. A reel cuts between a wide, a medium and a close-up, and
a median over the whole reel averages those into a number nobody framed to.

So the bands come from the POOLED PER-FRAME distribution across every reference,
split at its own terciles. That gives three sizes the corpus actually shoots,
each with a real range, rather than one number it never uses.

THE VARIATION NUMBER IS THE LOAD-BEARING ONE
--------------------------------------------
What separates the references from our reels is not where the median sits, it is
how far the reel travels. Corpus median variation is ~2.1x (p90/p10 of face size
within one reel) and only a handful sit below 1.35x. Our latest cut is 1.35x
with every check green — technically fine, visibly one shot repeated.

Sources: the 21-reel corpus plus the two reels supplied as framing references,
measured the same way at 270x480.
"""
import argparse
import io
import json
import pathlib
import statistics as st

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "refs" / "face-size.json"
OUT = ROOT / "refs" / "shot-bands.json"


def build():
    rows = json.loads(SRC.read_text(encoding="utf-8"))
    rows = [r for r in rows if r.get("samples")]
    pooled = np.array([v for r in rows for v in r["samples"]])
    if pooled.size < 100:
        raise SystemExit("not enough samples; re-run refs/face-size.py --json")

    t1, t2 = np.percentile(pooled, [33.3, 66.7])
    lo, hi = np.percentile(pooled, [2, 98])
    variation = [r["size_variation"] for r in rows if r.get("size_variation")]

    def band(name, a, b, note):
        sel = pooled[(pooled >= a) & (pooled < b)]
        return {
            "min": round(float(a), 3),
            "max": round(float(b), 3),
            "median": round(float(np.median(sel)), 3) if sel.size else None,
            "share_of_corpus_frames": round(100 * sel.size / pooled.size, 1),
            "note": note,
        }

    return {
        "_note": (
            "GENERATED by refs/shot-bands.py from refs/face-size.json. Face "
            "height as a fraction of frame height, measured at 270x480 with a "
            "Haar detector. Bands are the terciles of the POOLED per-frame "
            "distribution across all references — the sizes the corpus actually "
            "shoots. Do not quote a single global target; see rule V."
        ),
        "sources": {
            "reels": len(rows),
            "frames_with_a_face": int(pooled.size),
        },
        "bands": {
            "wide": band("wide", lo, t1,
                         "face small in frame: context, environment, an index "
                         "or thumbnail card, a subject among other things"),
            "medium": band("medium", t1, t2,
                           "head and shoulders with air above and below — the "
                           "corpus default, and what both supplied references "
                           "hold for most of their runtime"),
            "close": band("close", t2, hi,
                          "a feature fills the frame: use when the beat is "
                          "about a detail that cannot be read at medium"),
        },
        "variation": {
            "median": round(st.median(variation), 2),
            "min": round(min(variation), 2),
            "max": round(max(variation), 2),
            "recommended_min": 1.8,
            "note": (
                "p90/p10 of face height within one reel. This is the axis that "
                "separates the references from our reels: they travel ~2.1x, we "
                "sat at 1.35x with everything else green. 1.8 is set below the "
                "corpus median so it is a floor, not a target to hit exactly."
            ),
        },
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--show", action="store_true")
    ap.parse_args()

    d = build()
    OUT.write_text(json.dumps(d, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  "
          f"({d['sources']['reels']} reels, "
          f"{d['sources']['frames_with_a_face']} frames with a face)")
    print(f"\n{'band':10}{'range':>18}{'median':>9}{'% of frames':>13}")
    for k, v in d["bands"].items():
        print(f"{k:10}{f'{v['min']}-{v['max']}':>18}{v['median']:>9}"
              f"{v['share_of_corpus_frames']:>13}")
    va = d["variation"]
    print(f"\nwithin-reel variation: median {va['median']}x  "
          f"(range {va['min']}-{va['max']})  floor set at {va['recommended_min']}x")


if __name__ == "__main__":
    main()
