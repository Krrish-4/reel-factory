import React from "react";
import { Easing, interpolate, useCurrentFrame } from "remotion";
import { serifFont } from "../../fonts";
import { WORD_CUES, type WordCue } from "./words";

/**
 * Captions driven by MEASURED per-word frames.
 *
 * Identical in behaviour and styling to `preview/captions.tsx`, with one
 * difference: the cue table is a PROP rather than a module import, so this
 * component is not welded to one reel's words.ts. The preview reel's copy is
 * left exactly as it is — that cut is signed off — but any reel after this one
 * can reuse this component instead of forking it again.
 *
 * Why per-word frames at all: the shared `Captions` in protocol/atoms.tsx
 * meters words evenly across 85% of the cue's SLOT, and a slot runs through the
 * pause after the phrase. Words are therefore paced slower than the speech and
 * fall progressively further behind, worst at the end of every line. Moving cue
 * starts cannot fix it — the drift is inside the caption. Each word here
 * carries its own frame, generated by `docs/preview-review/gen-words-mirror.py`.
 */

const clamp = {
  extrapolateLeft: "clamp",
  extrapolateRight: "clamp",
} as const;

export const MirrorCaptions: React.FC<{ cues?: readonly WordCue[] }> = ({
  cues = WORD_CUES,
}) => {
  const frame = useCurrentFrame();
  return (
    <div
      style={{
        position: "absolute",
        bottom: "9%",
        left: 0,
        right: 0,
        height: 150,
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        padding: "0 70px",
      }}
    >
      {cues.map((c, i) => {
        if (frame < c.f - 6 || frame > c.t + 6) return null;
        const words = c.s.split(" ");
        const outO = interpolate(frame, [c.t - 7, c.t], [1, 0], clamp);
        return (
          <div
            key={i}
            style={{
              position: "absolute",
              textAlign: "center",
              fontFamily: serifFont,
              fontStyle: "italic",
              fontSize: 44,
              color: "#fff",
              lineHeight: 1.3,
              opacity: outO,
              textShadow: "0 2px 22px rgba(26,38,42,0.5)",
            }}
          >
            {words.map((w, k) => {
              const t0 = c.w[k] ?? c.f;
              const o = interpolate(frame, [t0, t0 + 5], [0, 1], clamp);
              const b = interpolate(frame, [t0, t0 + 6], [6, 0], clamp);
              const y = interpolate(frame, [t0, t0 + 7], [9, 0], {
                ...clamp,
                easing: Easing.out(Easing.quad),
              });
              /* Unshown words stay rendered at opacity 0 rather than being
                 omitted. They still occupy layout, so the centred line keeps
                 its final width and does not reflow as words arrive. */
              return (
                <span
                  key={k}
                  style={{
                    display: "inline-block",
                    opacity: o,
                    filter: `blur(${b}px)`,
                    transform: `translateY(${y}px)`,
                    marginRight: "0.26em",
                  }}
                >
                  {w}
                </span>
              );
            })}
          </div>
        );
      })}
    </div>
  );
};
