import React from "react";
import { Easing, interpolate, useCurrentFrame } from "remotion";
import { serifFont } from "../../fonts";
import { WORD_CUES } from "./words";

/**
 * Captions driven by MEASURED per-word frames.
 *
 * The shared `Captions` in protocol/atoms.tsx meters words evenly across 85% of
 * the cue's slot:
 *
 *     step = (t - f) * 0.85 / nwords
 *
 * A slot runs until 3 frames before the NEXT cue, so it covers the phrase *and*
 * the pause after it — but the voice is only speaking for the first part. Words
 * were therefore metered slower than the speech and fell progressively further
 * behind, worst at the end of every line. Fixing where a cue *starts* does not
 * help; the drift happens inside the caption. That is why moving cue frames
 * alone changed so little between v7 and v9.
 *
 * Here each word carries its own frame, generated by
 * `docs/preview-review/gen-words.py` from the voiceover: silence is removed and
 * the words are laid out along the remaining speech, with hand-measured
 * overrides where an emphasised word breaks the character-weighted estimate.
 *
 * The shared component is left untouched — `RefinaProtocolReel` is the approved
 * cut and imports it. This is a preview-local replacement, and the styling
 * matches it exactly (spec §3: italic serif, bottom track, word-by-word blur).
 */

const clamp = {
  extrapolateLeft: "clamp",
  extrapolateRight: "clamp",
} as const;

export const PreviewCaptions: React.FC = () => {
  const frame = useCurrentFrame();
  return (
    <div
      style={{
        position: "absolute",
        bottom: "9%",
        left: 0,
        right: 0,
        height: 150,
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        padding: "0 70px",
      }}
    >
      {WORD_CUES.map((c, i) => {
        if (frame < c.f - 6 || frame > c.t + 6) return null;
        const words = c.s.split(" ");
        const outO = interpolate(frame, [c.t - 7, c.t], [1, 0], clamp);
        return (
          <div
            key={i}
            style={{
              position: "absolute",
              textAlign: "center",
              fontFamily: serifFont,
              fontStyle: "italic",
              fontSize: 44,
              color: "#fff",
              lineHeight: 1.3,
              opacity: outO,
            }}
          >
            {words.map((w, k) => {
              const t0 = c.w[k] ?? c.f;
              const o = interpolate(frame, [t0, t0 + 5], [0, 1], clamp);
              const b = interpolate(frame, [t0, t0 + 6], [6, 0], clamp);
              const y = interpolate(frame, [t0, t0 + 7], [9, 0], {
                ...clamp,
                easing: Easing.out(Easing.quad),
              });
              /* Unshown words stay rendered at opacity 0 rather than being
                 omitted. They still occupy layout, so the centred line keeps
                 its final width and does not reflow as words arrive. */
              return (
                <span
                  key={k}
                  style={{
                    display: "inline-block",
                    opacity: o,
                    filter: `blur(${b}px)`,
                    transform: `translateY(${y}px)`,
                    marginRight: "0.26em",
                  }}
                >
                  {w}
                </span>
              );
            })}
          </div>
        );
      })}
    </div>
  );
};
