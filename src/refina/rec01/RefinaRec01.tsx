const CardOverlay: React.FC<{ opt: number; label?: string; v?: Variant }> = ({
  opt,
  label,
  v = "a",
}) => {
  const { x, y, w, h, r } = GEOM[v].win;
  const hole =
    `M0 0H1080V1920H0Z ` +
    `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}` +
    `A${r} ${r} 0 0 1 ${x + w - r} ${y + h}H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}` +
    `V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`;
  const mask = `url("data:image/svg+xml,${encodeURIComponent(
    `<svg xmlns='http://www.w3.org/2000/svg' width='1080' height='1920'><path fill-rule='evenodd' d='${hole}'/></svg>`,
  )}")`;
  return (
    <AbsoluteFill>
      <AbsoluteFill style={{ maskImage: mask, WebkitMaskImage: mask }}>
        <CardLayout
          v={v}
          opt={opt}
          label={label}
          question={opt === 2 ? 1 : 0}
          window={null}
        />
      </AbsoluteFill>
      <div
        style={{ position: "absolute", left: x, top: y, width: w, height: h }}
      >
        <Chrome v={v} opt={opt} />
      </div>
    </AbsoluteFill>
  );
};

