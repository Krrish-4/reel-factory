"""Generate `src/refina/changed/words.ts` from the script text.

    python docs/preview-review/gen-words-changed.py

THE SCRIPT BELOW IS THE SOURCE OF TRUTH. No frame number is typed anywhere in
this repo for this reel: cue starts, beat bounds and TOTAL are all derived from
word count here, and the composition addresses beats by NAME. Editing the
generated file by hand defeats that (invariant B).

ESTIMATED, NOT MEASURED. There is no voiceover yet. When one arrives, save it in
`public/`, switch this to `voscript.py`'s measure path the way
`gen-words-mirror.py` does, and re-run — every picture follows the words because
both read the same table.

THE RATE IS THE POINT. The 18 explainers in the reference corpus run 58s median
at 95.7% speech, roughly 205-240 wpm. Our own reels run 158 wpm at 74-85%
speech, and that gap is a large part of why ours read as advertising and theirs
read as teaching: an explainer does not pause for effect, it keeps handing you
the next fact. 205 wpm with 8-frame gaps lands at ~96% speech.
"""
import io
import os

FPS = 30
WPM = 205
GAP = 8  # frames of silence between lines; 8 keeps speech at ~96%

# (beat id, spoken line). One line per beat — this script has no beat that
# carries two sentences of VO, which is what keeps the picture changes and the
# sentence boundaries on the same frames.
LINES = [
    ("hook",     "One of these is before surgery. One is after. Watch what else changed."),
    ("claim",    "In most before-and-afters, the surgery isn't the only thing that moved. "
                 "Four other things did."),
    ("light",    "One. The light. Flat light from the front erases most of the shadow on a face. "
                 "Move it overhead and the folds and hollows come straight back. Same face, nothing touched."),
    ("distance", "Two. The distance. A phone at arm's length pushes the nose forward and pulls the "
                 "jaw in. Two steps back, and the whole face rebalances, with nothing done to it."),
    ("tilt",     "Three. The tilt. Chin down hides a jawline. Chin level gives you one. "
                 "That's a few degrees."),
    ("express",  "Four. The face you're making. A relaxed mouth and a slight lift move the midface "
                 "before anyone has touched it."),
    ("nuance",   "None of this means the surgery did nothing. It means you can't separate the "
                 "surgery from the photograph by looking at it. Both are true at once."),
    ("test",     "So test it yourself. Two photos, same room, a minute apart. Light in front, then "
                 "light above. You'll meet two different people."),
    ("standard", "The only comparison worth anything is the same face, same light, same lens, same "
                 "angle. Ask any gallery for that. Or see it on your own face first."),
]


def main():
    cues, bounds, f = [], {}, 0
    for bid, text in LINES:
        n = len(text.split())
        dur = round(n / WPM * 60 * FPS)
        cues.append((f, f + dur, text))
        bounds[bid] = (f, f + dur + GAP)
        f += dur + GAP
    total = f - GAP  # no trailing gap

    words = sum(len(t.split()) for _, t in LINES)
    speech = sum(b - a for a, b, _ in cues)

    out = ['/* Caption cues for "What Else Changed".',
           " *",
           " * GENERATED by docs/preview-review/gen-words-changed.py — do not hand-edit.",
           " * Edit the LINES table in that generator (the script's source of truth) and",
           " * re-run. Timing is ESTIMATED from word count at %d wpm; there is no" % WPM,
           " * voiceover yet. See the generator's header before re-timing.",
           " *",
           " * %d words, %d frames (%.1fs), %.1f%% speech." % (
               words, total, total / FPS, 100 * speech / total),
           " */",
           "export type WordCue = { f: number; t: number; s: string };",
           "",
           "export const CUES: WordCue[] = ["]
    for a, b, t in cues:
        out.append('  { f: %d, t: %d, s: %s },' % (a, b, ts_string(t)))
    out.append("];")
    out.append("")
    out.append("/** Beat bounds, derived from the cue frames above. */")
    out.append("export const B = {")
    for bid, _ in LINES:
        a, b = bounds[bid]
        out.append("  %-9s [%d, %d]," % (bid + ":", a, b))
    out.append("} as const;")
    out.append("")
    out.append("export const TOTAL = %d;" % total)
    out.append("")

    dest = os.path.join("src", "refina", "changed", "words.ts")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    io.open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote %s" % dest)
    print("  %d words, %d frames = %.1fs, %.1f%% speech (corpus explainers: 58s, 95.7%%)"
          % (words, total, total / FPS, 100 * speech / total))
    for bid, _ in LINES:
        a, b = bounds[bid]
        print("    %-9s f%-5d-%-5d  %4.1fs" % (bid, a, b, (b - a) / FPS))


def ts_string(t):
    return '"' + t.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main()
