"""The shot plan: declare each beat's composition and whether it moves, then check it.

    python gen/shots.py src/refina/changed/shots.json --emit
    python gen/shots.py src/refina/changed/shots.json --verify out/refina-changed-v2.mp4

WHY THIS EXISTS
---------------
Two failures repeat in every reel this repo has made, and neither is caught by
anything today.

  NOTHING MOVES. frozen 85.2 / 82.7 / 94.6 against a corpus median of 50.5;
  continuous motion 6.7 / 14.4 / 0.3 against 27.3. Three reels, three different
  visual languages, the same result -- because almost every beat is a still
  photograph with overlays arriving on top of it, which is not the same thing as
  a picture that moves.

  ONE COMPOSITION, REPEATED. `ratio-v5` used a single layout for all nine of its
  scenes (Gemini described every one as "full-bleed portrait"). `mirror2` reused
  its framed portrait three times. `changed` did not -- so this is fixable, and
  it is worth making structural rather than remembered.

DECLARATION, THEN MEASUREMENT
-----------------------------
`--emit` checks the PLAN: no two consecutive beats may share a composition, and
enough of the runtime must be declared moving. That is cheap and runs before a
render.

`--verify` checks the RENDER against the plan: a beat declared `moving` must
actually measure as moving. A declaration on its own is just a promise, and the
whole point of this repo's measurement work is that promises about a video are
checked against the video.

WHY NOT JUST FAIL ON frozen_pct
-------------------------------
Because that is the gameable version, and it was already gamed: a slow zoom was
added to a dead beat purely to move that number (rule P). This asserts something
structural instead -- "this beat is supposed to move, and it does not" names a
specific beat and a specific lie, which a global percentage never does.
"""
import argparse
import json
import pathlib
import re
import subprocess
import sys

import cv2
import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent.parent
BANDS = ROOT / "refs" / "shot-bands.json"
# 270x480, NOT the 160x284 measure-format.py uses. Rule U: at 160px a jawline
# change and a 2px slider handle are a fraction of a pixel, so a cut that moves
# continuously reads as frozen. This tool judges whether a beat moves, which is
# exactly the judgement that resolution destroys.
W, H = 270, 480
FPS = 30

# a frame counts as moving when a localised part of it changed; the same
# definition refs/measure-format.py uses for continuous motion
MOVE_LO, MOVE_HI = 0.02, 0.35
# a beat declared `moving` must have at least this share of its frames moving
MOVING_FRAME_SHARE = 0.30


def load(spec_path):
    spec = json.loads(pathlib.Path(spec_path).read_text(encoding="utf-8"))
    beats = spec["beats"]
    if not beats:
        raise SystemExit("shot plan has no beats")
    return spec, beats


def cue_bounds(cues_path, beats):
    """Beat frame bounds, from the generated cue table and the declared line counts."""
    src = pathlib.Path(cues_path).read_text(encoding="utf-8")
    rows = re.findall(r"\{ f: (\d+), t: (\d+),", src)
    if not rows:
        raise SystemExit(f"no cue table found in {cues_path}")
    declared = sum(b["lines"] for b in beats)
    if declared != len(rows):
        raise SystemExit(
            f"shot plan declares {declared} script lines but {cues_path} has "
            f"{len(rows)}. Re-run gen-voiceover.py, then fix `lines` to match."
        )
    out, i = [], 0
    for b in beats:
        a = int(rows[i][0])
        z = int(rows[i + b["lines"] - 1][1])
        out.append((b, a, z))
        i += b["lines"]
    return out


def emit(spec, beats, dest):
    lines = [
        "/* GENERATED by gen/shots.py from shots.json -- do not hand-edit.",
        " *",
        " * The shot plan: what each beat looks like and whether it moves.",
        " * `lines` is the number of script phrases the beat covers and is the",
        " * single declaration of beat structure -- beats.ts derives its bounds",
        " * from here, so the script, the cue table and the shot plan cannot",
        " * disagree without failing.",
        " */",
        "/** Anything a beat component may be handed from the spec. */",
        "export type BeatProps = {",
        "  under?: string; over?: string; zoom?: number; focus?: string;",
        "  dir?: string; wipe?: string; period?: number; dim?: number;",
        "  reticle?: string; reticleLabel?: string; tag?: string;",
        "  tags?: string[]; steps?: string[]; locked?: string[];",
        "  compliance?: boolean; lamp?: boolean; track?: boolean;",
        "  boxed?: boolean; fan?: boolean; mesh?: boolean; fold?: boolean;",
        "  chips?: string; type?: string;",
        "  // RefinaFlip. Its second picture is always a DERIVED asset -- a flip,",
        "  // a half doubled onto its own mirror, or a difference map -- so it",
        "  // needs a pair of half-assets rather than one `over`, a turn count,",
        "  // band captions, and the key of the mirror measurement a beat prints.",
        "  left?: string; right?: string; turns?: number; fit?: number;",
        "  bands?: string[]; measure?: string;",
        "  // RefinaLips. Its spans are drawn between MEASURED landmarks rather",
        "  // than the fixed REGIONS boxes (which are identical on a before and",
        "  // its after, so a philtrum span from them would show no change on the",
        "  // one beat whose claim is that the gap shortens). `band` names which",
        "  // landmark pair to bracket; `held` says the two are the same length",
        "  // and that is the point.",
        "  sweeps?: number; rules?: string[]; subject?: string;",
        "  band?: string; labels?: string[]; caption?: string;",
        "  held?: boolean; note?: string;",
        "  // RefinaNose. It draws WHERE, never HOW MUCH, on the face itself:",
        "  // `ringHeld` names the region that did NOT change and `ringChanged`",
        "  // the one that did, both positioned from the asset record by",
        "  // anchor(). There are deliberately no spans -- this pair's lower",
        "  // third does not change HEIGHT, so a bracket across it would draw a",
        "  // difference that is not there (invariant HH, and see the module",
        "  // docstring of gen/emit-nose.py for the measurement that says so).",
        "  // `assetTag` suppresses the record label on a beat that is still",
        "  // posing the question the label would answer.",
        "  ringHeld?: string; ringChanged?: string;",
        "  ringHeldLabel?: string; ringChangedLabel?: string;",
        "  assetTag?: boolean; settle?: number;",
        "  // RefinaNose framing. The picture COVERS the frame (its master is",
        "  // padded by gen/extend-frame.py), so there is no `fit` here: framing",
        "  // is `zoom` plus a `focus` SOLVED from the asset record to park the",
        "  // face at `faceY`. `push` then lands on the script line that names a",
        "  // feature and travels to that feature's measured box -- the reel",
        "  // pointing at what it is talking about, not a creep added to move a",
        "  // number (rule P). `panel` is the nuance beat's window width.",
        "  faceY?: number; panel?: number; panelH?: number;",
        "  push?: { target: string; zoom: number; line: number; y?: number; dur?: number };",
        "};",
        "",
        "export type Shot = {",
        "  name: string;",
        "  lines: number;",
        "  composition: string;",
        "  motion: \"moving\" | \"static\";",
        "  shot: string;",
        "  props: BeatProps;",
        "};",
        "",
        "export const SHOTS = [",
    ]
    for b in beats:
        props = json.dumps(b.get("props", {}))
        lines.append(
            f'  {{ name: "{b["name"]}", lines: {b["lines"]}, '
            f'composition: "{b["composition"]}", motion: "{b["motion"]}", '
            f'shot: "{b.get("shot", "medium")}", props: {props} as BeatProps }},'
        )
    lines += ["] as const satisfies readonly Shot[];", "",
              "export type BeatName = (typeof SHOTS)[number][\"name\"];", ""]
    dest = pathlib.Path(dest)
    dest.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return dest


def check_plan(spec, beats):
    fails = []
    for a, b in zip(beats, beats[1:]):
        if a["composition"] == b["composition"]:
            fails.append(
                f"'{a['name']}' and '{b['name']}' are consecutive and share the "
                f"composition '{a['composition']}' — vary the shot"
            )
    for b in beats:
        if b["motion"] not in ("moving", "static"):
            fails.append(f"'{b['name']}' has motion={b['motion']!r}")
    names = set(load_bands()["bands"])
    for b in beats:
        if b.get("shot") not in names:
            fails.append(
                f"'{b['name']}' declares shot={b.get('shot')!r}; must be one of "
                f"{sorted(names)} (see refs/shot-bands.json)"
            )
    if len({b.get("shot") for b in beats}) < 2:
        fails.append(
            "every beat declares the same shot size — the corpus travels ~2.1x "
            "within a reel and only a handful sit below 1.35x"
        )
    return fails


def load_bands():
    """Shot-size bands, derived from the corpus by refs/shot-bands.py.

    Never a hand-typed number: rule V. The bands are terciles of the pooled
    per-frame face-height distribution across the 21-reel corpus plus the two
    supplied framing references — the sizes those reels actually shoot.
    """
    if not BANDS.is_file():
        raise SystemExit(f"missing {BANDS}. Run refs/shot-bands.py first.")
    return json.loads(BANDS.read_text(encoding="utf-8"))


def face_heights(video, spans, every=5):
    """Median face height per beat, as a fraction of frame height.

    THE START INDEX ROUNDS UP, NOT DOWN. Sampling every `every`th frame, a beat
    starting at frame 922 has its first sample at 925; `922 // 5` is 184, which
    is source frame 920 and belongs to the PREVIOUS beat. That mattered the
    first time a beat with no portrait in it followed one with a portrait:
    RefinaNose's `test` beat is three instruction cards and no face, and the
    only "face" in its 39 samples was frame 920 — the tail of the portrait beat
    before it. A median over that single borrowed frame reported 0.369 and
    failed the beat for being framed as a close-up, which is a shot size it does
    not have because it has no face at all.

    The floor could quietly misattribute up to `every - 1` frames of any beat to
    the one after it. It only ever changes a verdict where the two beats differ
    in what they show, which is precisely a scene boundary.
    """
    casc = cv2.CascadeClassifier(
        cv2.data.haarcascades + "haarcascade_frontalface_default.xml")
    cmd = ["ffmpeg", "-v", "error", "-i", str(video), "-vf",
           f"select=not(mod(n\\,{every})),scale={W}:{H}", "-vsync", "0",
           "-pix_fmt", "gray", "-f", "rawvideo", "-"]
    raw = subprocess.run(cmd, capture_output=True).stdout
    n = len(raw) // (W * H)
    fr = np.frombuffer(raw, np.uint8)[: n * W * H].reshape(n, H, W)

    out = {}
    for b, a, z in spans:
        hs = []
        for i in range(-(-a // every), min(z // every, n)):
            g = cv2.equalizeHist(fr[i])
            faces = casc.detectMultiScale(g, scaleFactor=1.12, minNeighbors=5,
                                          minSize=(24, 24))
            if len(faces):
                hs.append(max(faces, key=lambda f: f[2] * f[3])[3] / H)
        out[b["name"]] = float(np.median(hs)) if hs else None
    return out


def measure(video, spans):
    cmd = ["ffmpeg", "-v", "error", "-i", str(video), "-vf",
           f"scale={W}:{H},format=gray", "-f", "rawvideo", "-"]
    raw = subprocess.run(cmd, capture_output=True).stdout
    g = np.frombuffer(raw, np.uint8)
    n = g.size // (W * H)
    g = g[: n * W * H].reshape(n, H, W).astype(np.int16)
    d = np.abs(np.diff(g, axis=0))
    # tile the frame; a frame is "moving" when a LOCAL part of it changed, not
    # when the whole picture flipped (that is a cut) and not when nothing did
    ty, tx = 8, 8
    th, tw = H // ty, W // tx
    tiles = d[:, : ty * th, : tx * tw].reshape(-1, ty, th, tx, tw)
    active = (tiles.mean(axis=(2, 4)) > 3.0).mean(axis=(1, 2))
    moving = (active > MOVE_LO) & (active < MOVE_HI)

    out = []
    for b, a, z in spans:
        seg = moving[a: max(a + 1, z - 1)]
        out.append((b, a, z, float(seg.mean()) if seg.size else 0.0))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("spec")
    ap.add_argument("--emit", action="store_true")
    ap.add_argument("--verify", metavar="VIDEO")
    a = ap.parse_args()

    spec, beats = load(a.spec)
    fails = check_plan(spec, beats)
    spans = cue_bounds(ROOT / spec["cues"], beats)
    total = spans[-1][2] - spans[0][1]
    moving_frames = sum(z - s for b, s, z in spans if b["motion"] == "moving")
    share = moving_frames / total
    need = spec.get("min_moving_share", 0.35)

    print(f"shot plan: {len(beats)} beats, {len(set(b['composition'] for b in beats))} "
          f"distinct compositions")
    print(f"  declared moving: {share:.0%} of runtime (minimum {need:.0%})")
    if share < need:
        fails.append(
            f"only {share:.0%} of runtime is declared moving, below the "
            f"{need:.0%} this plan sets"
        )

    if a.emit and not fails:
        dest = emit(spec, beats, pathlib.Path(a.spec).resolve().with_suffix(".ts"))
        print(f"  wrote {dest.relative_to(ROOT)}")

    if a.verify:
        print(f"\nmeasured against {a.verify}:")
        for b, s, z, m in measure(ROOT / a.verify, spans):
            want = b["motion"] == "moving"
            ok = (m >= MOVING_FRAME_SHARE) if want else True
            flag = "" if ok else "   <-- declared moving, is not"
            print(f"  {b['name']:9} {b['composition']:22} "
                  f"{b['motion']:7} {m:5.0%} of frames move{flag}")
            if not ok:
                fails.append(
                    f"'{b['name']}' is declared moving but only {m:.0%} of its "
                    f"frames move (needs {MOVING_FRAME_SHARE:.0%}). Either the "
                    f"beat does not do what the plan says, or the plan is wrong."
                )

        bands = load_bands()
        fh = face_heights(ROOT / a.verify, spans)
        seen = [v for v in fh.values() if v]
        print("\n  face size per beat (bands from refs/shot-bands.json):")
        for b in beats:
            v = fh.get(b["name"])
            band = bands["bands"][b["shot"]]
            if v is None:
                print(f"  {b['name']:9} {b['shot']:7}  no face detected")
                continue
            ok = band["min"] <= v <= band["max"]
            print(f"  {b['name']:9} {b['shot']:7} {v:5.3f}  "
                  f"band {band['min']}-{band['max']}"
                  + ("" if ok else "   <-- outside"))
            if not ok:
                fails.append(
                    f"'{b['name']}' declares {b['shot']} but its face measures "
                    f"{v:.3f}, outside {band['min']}-{band['max']}"
                )
        if len(seen) > 1:
            var = max(seen) / max(1e-6, min(seen))
            floor = bands["variation"]["recommended_min"]
            print(f"\n  shot-size travel across the reel: {var:.2f}x "
                  f"(corpus median {bands['variation']['median']}x, floor {floor}x)")
            if var < floor:
                fails.append(
                    f"the reel only travels {var:.2f}x in face size, below the "
                    f"{floor}x floor. The references get their range by cutting "
                    f"to compositions that are not portraits — index cards, "
                    f"real-world photos, insets — not by resizing one portrait."
                )

    if fails:
        print()
        for f in fails:
            print(f"  FAIL  {f}")
        print(f"\n{len(fails)} failure(s)")
        return 1
    print("\nshot plan holds")
    return 0


if __name__ == "__main__":
    sys.exit(main())
