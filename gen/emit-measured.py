"""Emit a reel's measured region numbers as TypeScript.

    python gen/emit-measured.py gen/out/subjects-20260829-165030/results.json \
        --subject ratio1 --after chin --ts src/refina/ratio/measured.ts

"Same Nose" is the first reel that puts a MEASUREMENT on screen, and a figure
typed into a composition is a figure that can drift away from the thing it
claims to describe. The same argument that made `words-vo.ts` generated applies
here with more force: caption timing that drifts looks sloppy, but a printed
per-region number that no longer matches its own pair is a false claim about an
image, which is what `docs/reel-invariants.md` rule E is about.

So the beat reads these out of a generated file. Re-run the scorer, re-run this,
and the chips on screen follow. Nothing in `src/refina/ratio/` types a number
about a face.
"""
import argparse
import io
import json
import pathlib


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("results", type=pathlib.Path)
    ap.add_argument("--subject", required=True)
    ap.add_argument("--after", required=True)
    ap.add_argument("--ts", required=True)
    a = ap.parse_args()

    rows = json.loads(a.results.read_text(encoding="utf-8"))
    sub = next((r for r in rows if r["subject"] == a.subject), None)
    if sub is None:
        raise SystemExit(f"no subject {a.subject} in {a.results}")
    aft = next((x for x in sub["afters"] if x["id"] == a.after), None)
    if aft is None:
        raise SystemExit(f"no after {a.after} for {a.subject}")
    if not aft.get("passed"):
        raise SystemExit(
            f"{a.subject}/{a.after} did not pass the localisation screen "
            f"({aft.get('reason')}) — refusing to publish its numbers as evidence"
        )

    r = aft["regions"]
    out = [
        "/* GENERATED by gen/emit-measured.py - do not hand-edit.",
        " *",
        f" * Region change for the pair {a.subject}/{a.after}, measured by",
        " * gen/score.py: p90 of per-pixel difference inside each anatomical box,",
        " * on the skin mask, after both images were put on one frame.",
        " *",
        " * The reel PRINTS these. Edit the pair, re-run the scorer, re-run this.",
        " */",
        "export type RegionScore = { region: string; value: number; target: boolean };",
        "",
        "export const REGION_CHANGE: RegionScore[] = [",
    ]
    for name in ("nose", "eyes", "jaw"):
        out.append(
            '  { region: "%s", value: %.1f, target: %s },'
            % (name.upper(), r[name], "true" if name == aft["target"] else "false")
        )
    out += [
        "];",
        "",
        "/** target region change divided by the loudest region it should have left alone */",
        "export const CONCENTRATION = %.2f;" % aft["concentration"],
        "/** median change over all facial skin — how much re-rendered underneath */",
        "export const DRIFT = %.1f;" % aft["drift"],
        "",
    ]
    io.open(a.ts, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("wrote %s" % a.ts)
    for name in ("nose", "eyes", "jaw"):
        print("  %-5s %5.1f%s" % (name, r[name], "  <- target" if name == aft["target"] else ""))
    print("  concentration %.2f, drift %.1f" % (aft["concentration"], aft["drift"]))


if __name__ == "__main__":
    main()
