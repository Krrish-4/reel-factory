"""Emit docs/beat-catalog.md: which beat animation carried which script lines.

    python gen/beat-catalog.py

Every spec-driven reel declares its beats in src/refina/<reel>/shots.json:
each beat covers `lines` phrases of the script and names the `composition`
(the beat animation / transition component) that draws them. This walks all
of them, re-attaches the actual script lines, and writes two views:

  1. by composition -- "what has full-bleed-wipe been used to say?"
  2. by reel        -- the full script -> animation storyboard of each reel

Use view 1 when writing a new shots.json: find a past beat whose LINES make
the same kind of move as yours (a reveal, a list item, a test-it-yourself, a
CTA) and start from its composition + props. Never hand-edit the output.
"""
import json
import pathlib
import re
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "beat-catalog.md"


def script_lines(path: pathlib.Path) -> list[str]:
    if not path.exists():
        return []
    out = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        s = raw.strip()
        if not s or s.startswith("#"):
            continue
        out.append(re.split(r"\s+\|\s*[\d.]+\s*$", s)[0].strip())
    return out


def main() -> None:
    by_comp = defaultdict(list)
    reels = []
    for spec in sorted(ROOT.glob("src/refina/*/shots.json")):
        d = json.loads(spec.read_text(encoding="utf-8"))
        reel = d.get("reel") or spec.parent.name
        lines = script_lines(ROOT / d["script"]) if d.get("script") else []
        i, rows = 0, []
        for b in d["beats"]:
            n = b.get("lines", 0)
            said = lines[i:i + n] if lines else []
            i += n
            row = {
                "reel": reel, "dir": spec.parent.name, "beat": b["name"],
                "composition": b["composition"], "motion": b.get("motion", ""),
                "shot": b.get("shot", ""), "said": said,
                "props": sorted((b.get("props") or {}).keys()),
            }
            rows.append(row)
            by_comp[b["composition"]].append(row)
        reels.append((reel, spec.parent.name, d.get("script", ""), rows))

    md = ["# Beat catalog -- which animation carried which script lines",
          "",
          "GENERATED by `gen/beat-catalog.py` from every `src/refina/*/shots.json`"
          " and its script. Do not hand-edit; re-run after adding a reel.",
          "",
          "A beat's `composition` is the animation/transition component that draws"
          " it (looked up in the reel's beat registry, props from `shots.json`)."
          " To build a new reel: write the script, then for each beat find the"
          " closest past line below and start from that composition. Rules that"
          " constrain the choice (no two adjacent beats share a composition,"
          " enough runtime moving, shot-size travel) are in"
          " `.claude/skills/refina-reel/reel-build/REFERENCE.md`; measured"
          " transition timings/easings are in `docs/qoves-motion-reference.md`.",
          "",
          "## By composition", ""]
    for comp in sorted(by_comp, key=lambda c: (-len(by_comp[c]), c)):
        uses = by_comp[comp]
        md.append(f"### `{comp}` -- {len(uses)} use(s)")
        md.append("")
        for r in uses:
            said = " / ".join(r["said"]) or "_(script not found)_"
            md.append(f"- **{r['dir']} - {r['beat']}** ({r['motion']}, {r['shot']}): {said}")
        props = sorted({p for r in uses for p in r["props"]})
        if props:
            md.append(f"  - props seen: `{'`, `'.join(props)}`")
        md.append("")
    md += ["## By reel (storyboards)", ""]
    for reel, d, script, rows in reels:
        md.append(f"### {reel} (`src/refina/{d}/`, script `{script}`)")
        md.append("")
        md.append("| beat | composition | motion | shot | lines |")
        md.append("|---|---|---|---|---|")
        for r in rows:
            said = "<br>".join(x.replace("|", "\\|") for x in r["said"])
            md.append(f"| {r['beat']} | `{r['composition']}` | {r['motion']} | {r['shot']} | {said} |")
        md.append("")
    OUT.write_text("\n".join(md), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(by_comp)} compositions across {len(reels)} reels")


if __name__ == "__main__":
    main()
