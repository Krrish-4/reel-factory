"""Emit src/refina/glowup/<reel>/data.ts from the measured files.

  python gen/glowup/emit.py --reel s2

Reads public-glowup/<reel>/words.json (ElevenLabs alignment, already rescaled
for any atempo) and portraits/landmarks.json (gen/glowup/portraits.py).
Writes WORDS (frame-accurate, 30fps) and PORTRAITS. Never hand-edit data.ts:
re-run this after a new VO or new stills and every beat follows.
"""
import argparse, json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FPS = 30


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reel", default="s2")
    a = ap.parse_args()
    pub = ROOT / "public-glowup" / a.reel
    w = json.loads((pub / "words.json").read_text())["words"]
    lm = json.loads((pub / "portraits" / "landmarks.json").read_text())
    words = [{"t": x["text"], "w": x["word"], "f0": round(x["start"] * FPS), "f1": max(round(x["end"] * FPS), round(x["start"] * FPS) + 1)} for x in w]
    # phrase cues in the house caption format (refina-reel captions: {s, f, t, w[]}),
    # split at clause punctuation, max 7 words so a line fits at 42px
    # A break is punctuation OR a real pause in the read (the script's dashes
    # are dropped from the word list, so "philtrum - not" only survives as a
    # gap). A one-word tail ("view.", "3D.", "app.") is folded back into its line.
    groups, cur = [], []
    for i, x in enumerate(words):
        cur.append(x)
        nxt = words[i + 1] if i + 1 < len(words) else None
        gap = nxt["f0"] - x["f1"] if nxt else 99
        if x["t"][-1:] in ".?!,;:" or gap >= 7 or len(cur) >= 7 or nxt is None:
            groups.append(cur)
            cur = []
    merged = []
    for g in groups:
        if merged and len(g) == 1 and merged[-1][-1]["t"][-1:] not in ".?!,;:" and len(merged[-1]) <= 8:
            merged[-1] = merged[-1] + g
        else:
            merged.append(g)
    cues = []
    for k, g in enumerate(merged):
        end = g[-1]["f1"] + 8
        if k + 1 < len(merged):
            end = min(end, merged[k + 1][0]["f0"] - 1)
        cues.append({"s": " ".join(c["t"] for c in g), "f": g[0]["f0"], "t": end, "w": [c["f0"] for c in g]})
    out = ROOT / "src/refina/glowup" / a.reel / "data.ts"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// GENERATED by gen/glowup/emit.py -- do not edit. Re-run after a new VO or new stills.\n"
        "import type { Landmarks } from '../kit';\n\n"
        f"export const VO_FRAMES = {round(w[-1]['end'] * FPS)};\n"
        f"export const WORDS: {{ t: string; w: string; f0: number; f1: number }}[] = {json.dumps(words)};\n\n"
        f"export const CUES: {{ s: string; f: number; t: number; w: number[] }}[] = {json.dumps(cues)};\n\n"
        f"export const PORTRAITS: Record<string, Landmarks> = {json.dumps(lm, indent=1)};\n"
    )
    print(f"{out}: {len(words)} words, VO {w[-1]['end']:.2f}s, portraits: {', '.join(lm)}")


if __name__ == "__main__":
    main()
