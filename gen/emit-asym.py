"""Write the mirror measurement into TypeScript, so no figure is typed by hand.

    python gen/emit-asym.py bleph1 demo1 --ts src/refina/flip/measured.ts

Sibling of `gen/emit-measured.py`, which does the same job for the procedure
scorer feeding "Same Nose". The argument is invariant B's, applied to evidence
rather than to timing: a number printed against a picture is a claim, and a
claim that has drifted from the file it describes is a false one (rule E), not
merely untidy. So the composition maps over this table and never spells a digit.

Re-run `gen/asym.py <name> --emit <stem>` and then this, and every chip in the
reel follows the new measurement.

WHAT THE NUMBERS ARE, EXACTLY
    Per-pixel absolute difference (max across RGB) between the registered
    master and its own horizontal mirror, over facial skin only, about the axis
    that makes that face as symmetric as it can be. `p90` is the 90th
    percentile — "how big is the disagreement where the two actually disagree".
    They describe TWO IMAGE FILES. They are not a measurement of a person, and
    the on-screen label says so.
"""
import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
PORTRAITS = ROOT / "public" / "portraits"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stems", nargs="+", help="stems passed to gen/asym.py --emit")
    ap.add_argument("--ts", required=True)
    a = ap.parse_args()

    rows = []
    for stem in a.stems:
        p = PORTRAITS / f"{stem}-asym.json"
        if not p.is_file():
            raise SystemExit(f"no {p.name} — run gen/asym.py <name> --emit {stem} first")
        rows.append((stem, json.loads(p.read_text(encoding="utf-8"))))

    out = [
        "/* GENERATED by gen/emit-asym.py -- do not hand-edit.",
        " *",
        " * The mirror measurement for every subject in RefinaFlip. Each figure is",
        " * the per-pixel absolute difference between a registered master and its",
        " * own horizontal mirror, over facial skin, about the axis that makes that",
        " * face as symmetric as it can be -- so every number is a LOWER BOUND.",
        " *",
        " * These describe two image files, not a person. The composition prints them",
        " * under a label that says exactly that, and types no digit of its own:",
        " * a figure that had drifted from the file it describes would be a false",
        " * claim (invariant E), which is why it is generated rather than written.",
        " */",
        "export type AsymMeasure = {",
        "  subject: string;",
        "  source: string;",
        "  /** 90th percentile difference, photo vs its mirror, on facial skin */",
        "  p90: number;",
        "  median: number;",
        "  mean: number;",
        "  /** same measurement inside each anatomical box */",
        "  regions: { eyes: number; nose: number; jaw: number };",
        "  /** how far the solved midline sits from the face centre, in source px */",
        "  axisOffsetPx: number;",
        "  /** skin pixels compared */",
        "  px: number;",
        "};",
        "",
        "export const ASYM = {",
    ]
    for stem, r in rows:
        g = r["regions"]
        out.append(
            f'  "{stem}": {{ subject: "{stem}", source: "{r["source"]}", '
            f'p90: {r["p90"]:.1f}, median: {r["median"]:.1f}, mean: {r["mean"]:.2f}, '
            f'regions: {{ eyes: {g["eyes"]:.1f}, nose: {g["nose"]:.1f}, '
            f'jaw: {g["jaw"]:.1f} }}, '
            f'axisOffsetPx: {r["axis_offset_px"]:.1f}, px: {r["px"]} }},'
        )
    out += [
        "} as const satisfies Record<string, AsymMeasure>;",
        "",
        "export type AsymSubject = keyof typeof ASYM;",
        "",
        "/** The label these figures may appear under. Naming the operation is what",
        " *  keeps the beat a statement about two files rather than about a face. */",
        'export const ASYM_LABEL = "PER-PIXEL DIFFERENCE, THIS PHOTO vs ITS MIRROR";',
        "",
    ]

    dest = ROOT / a.ts
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {a.ts}  ({len(rows)} subjects)")
    for stem, r in rows:
        print(f"  {stem}: p90 {r['p90']:.1f}  median {r['median']:.1f}  "
              f"axis {r['axis_offset_px']:+.1f}px  {r['px']} px compared")


if __name__ == "__main__":
    main()
