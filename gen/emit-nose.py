"""Emit src/refina/nose/measured.ts — the numbers RefinaNose is allowed to draw.

    python gen/emit-nose.py ratio1 --after chin --ts src/refina/nose/measured.ts

Invariant B applied to EVIDENCE rather than to timing: no figure about a face is
typed into the composition. What comes out is per-region pixel change between
the registered before and after, from `gen/score.py`'s own machinery — a
statement about two IMAGE FILES, which is the only kind of measurement this repo
prints (rule E).

WHY THERE ARE NO LANDMARKS HERE, unlike gen/emit-lips.py
--------------------------------------------------------
RefinaLips measures noseBase / lipTop / mouthLine because its claim is that a
VERTICAL distance shortens, and the fixed REGIONS boxes are identical on a
before and its after so they could never show it (invariant HH).

This reel has the opposite problem and it was found by measuring rather than
assumed. On the aligned ratio1 pair:

    face height              1070 -> 1059 px   (SHORTER)
    nose base to chin bottom  375 ->  375 px   (unchanged)
    lower-face width @0.75    572 ->  628 px   (+9.8%)

So the lower third does NOT get longer, and a vertical span across it would
draw a difference that is not there — exactly the fault invariant HH names,
and one that would have passed every check in the repo. The width figure is
real but not usable either: the same skin-mask measurement reports the EYE-LINE
width moving 739 -> 788 px on a region no brief touched, so its edges are
contaminated (hair, jaw shadow) and it cannot carry a printed claim.

The reel therefore draws WHERE, never HOW MUCH, on the face itself: `Ring` over
the nose and the jaw, positioned from the asset record. The only quantities on
screen are these region scores, beside the difference map they were computed
from — one pixel set, one set of numbers (rule Z).
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from align_core import align, face_mask, global_drift, region_score  # noqa: E402

PORTRAITS = HERE.parent / "public" / "portraits"
REGISTRY = PORTRAITS / "registry.json"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("subjects", nargs="+", help="subject ids, e.g. ratio1")
    ap.add_argument("--after", default="chin", help="suffix of the after asset")
    ap.add_argument("--target", default="jaw", help="the region the edit is meant to move")
    ap.add_argument("--ts", type=pathlib.Path, required=True)
    a = ap.parse_args()

    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    scores = {}
    for subj in a.subjects:
        before, after = f"{subj}-before", f"{subj}-{a.after}"
        for n in (before, after):
            if n not in reg:
                raise SystemExit(f"{n} is not registered — run gen/registry.py --ingest")
        aligned, anc = align([("b", PORTRAITS / reg[before]["file"]),
                              ("c", PORTRAITS / reg[after]["file"])])
        mask = face_mask(aligned["b"], anc)
        d = region_score(aligned["b"], aligned["c"], anc, mask)
        drift = global_drift(aligned["b"], aligned["c"], anc, mask)
        others = max(v for k, v in d.items() if k != a.target)
        scores[subj] = {
            "eyes": round(d["eyes"], 1), "nose": round(d["nose"], 1),
            "lips": round(d["lips"], 1), "jaw": round(d["jaw"], 1),
            "concentration": round(d[a.target] / others, 2),
            "drift": round(drift, 1),
        }
        s = scores[subj]
        print(f"{subj}: eyes {s['eyes']} nose {s['nose']} lips {s['lips']} "
              f"jaw {s['jaw']}  conc {s['concentration']} drift {s['drift']}")
        # The reel says "almost none of it is on her nose". That line is only
        # true if the nose is the QUIETEST region, and it is checked here rather
        # than trusted -- ratio.txt and lips.txt were both rewritten when the
        # measurement disagreed with the words, and this is that gate in code.
        if s["nose"] != min(s["eyes"], s["nose"], s["lips"], s["jaw"]):
            raise SystemExit(
                f"{subj}: nose is not the quietest region ({s}). The script says "
                f"'almost none of it is on her nose' — rewrite the line or recast "
                f"the pair; do not print this number under that sentence (rule E)."
            )
        if s["nose"] >= s["jaw"] * 0.5:
            raise SystemExit(
                f"{subj}: nose {s['nose']} is not clearly quieter than jaw "
                f"{s['jaw']}. The hook does not survive this pair."
            )

    out = [
        "/* GENERATED by gen/emit-nose.py - do not hand-edit.",
        " *",
        " * Per-region pixel change between two registered image files, measured",
        " * over facial skin by align_core.region_score at the 90th percentile.",
        " * These describe the two FILES, never the face in them - which is the",
        " * only kind of figure this repo puts on screen (rule E).",
        " *",
        " * There are deliberately no landmark geometries here. See the module",
        " * docstring of gen/emit-nose.py: this pair's lower third does not change",
        " * HEIGHT, so a vertical span across it would draw a difference that is",
        " * not there (invariant HH).",
        " */",
        "export type NoseScore = { eyes: number; nose: number; lips: number; jaw: number;"
        " concentration: number; drift: number };",
        f"export const SCORES: Record<string, NoseScore> = {json.dumps(scores, indent=2)};",
        "",
    ]
    a.ts.parent.mkdir(parents=True, exist_ok=True)
    a.ts.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {a.ts}")


if __name__ == "__main__":
    main()
